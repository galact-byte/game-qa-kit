-- Run the production state machine with synthetic timestamps and no engine input.
local M = dofile('GameQaBridge.lua')
local session = string.rep('a', 32)
local results = {}
local function test(name, fn)
    local ok, err = pcall(fn)
    results[#results+1] = (ok and 'PASS ' or 'FAIL ') .. name .. (ok and '' or ': ' .. tostring(err))
end
local function command(seq, kind, lease, hold, token)
    return string.format('GQA1 %s 42 %d %d %d %d\n', token or session, seq, kind, lease, hold or 0)
end
local function resumed()
    local s = M.new(session, 42)
    s:update(command(1,1,2500),1000)
    s:consumed(false,1,1000)
    assert(s.ack_seq==1 and s.ack_kind==1 and not s.paused)
    return s
end

test('new session does not hold or infer a consumed command', function()
    local s=M.new(session,42)
    assert(s.paused and not s.desired and s.ack_seq==0)
end)
test('writing down is not consumption', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    assert(s.desired and s.ack_seq==1)
    s:consumed(false,2,1010); assert(s.ack_seq==1)
    s:consumed(true,3,1020); assert(s.ack_seq==2 and s.held)
end)
test('release needs a normal query returning released', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000); s:consumed(true,2,1000)
    s:update(command(3,3,2500),1100); s:consumed(true,3,1100); assert(s.ack_seq==2)
    s:consumed(false,4,1120); assert(s.ack_seq==3 and s.ack_kind==3 and not s.held)
end)
test('same command heartbeat cannot extend hold', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    s:update(command(2,2,2600,1600),1100); assert(s.desired)
    s:update(command(2,2,3000,1600),1600); assert(not s.desired)
    s:update(command(2,2,3100,1600),1700); assert(not s.desired)
end)
test('mutated replay clears input', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    s:update(command(2,2,2600,1700),1100); assert(s.paused and not s.desired and s.reason=='invalid')
end)
test('lease expiry cannot be revived by old down or resume', function()
    local s=resumed(); s:update(command(2,2,1500,1400),1000)
    s:update(command(2,2,1500,1400),1500); assert(s.paused and not s.desired)
    s:update(command(2,2,2900,1400),1501); assert(s.paused and not s.desired)
end)
test('past down is not applied after stop', function()
    local s=resumed(); s:update(command(2,2,2500,1200),1700)
    assert(not s.desired and s.reason=='action_expired')
end)
test('short read removes existing override request', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    s:update('GQA1',1100); assert(s.paused and not s.desired)
end)
test('missing channel removes existing override request', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    s:update(nil,1100); assert(s.paused and not s.desired)
end)
test('wrong session cannot press', function()
    local s=resumed(); s:update(command(2,2,2500,1600,string.rep('b',32)),1100)
    assert(s.paused and not s.desired)
end)
test('unknown pid cannot press', function()
    local s=resumed(); s:update(command(2,2,2500,1600):gsub(' 42 ',' 43 '),1100)
    assert(s.paused and not s.desired)
end)
test('stale command cannot restore an older generation', function()
    local s=resumed(); s:update(command(2,4,2500),1100); s:consumed(false,2,1100)
    s:update(command(1,1,2500),1200); assert(s.paused and not s.desired)
end)
test('down while paused cannot enable input', function()
    local s=M.new(session,42); s:update(command(1,2,2500,1600),1000)
    assert(s.paused and not s.desired)
end)
test('manual pause needs a new consumption acknowledgement', function()
    local s=resumed(); s:update(command(2,4,2500),1100)
    assert(s.ack_seq==1); s:consumed(false,2,1100)
    assert(s.paused and s.ack_seq==2 and s.ack_kind==4)
end)
test('right deadline wraps safely', function()
    local s=M.new(session,42); local n=2147483500
    s:update(command(1,1,1000),n); s:consumed(false,1,n)
    s:update(command(2,2,1000,200),n); assert(s.desired)
    s:update(command(2,2,1000,200),201); assert(not s.desired)
end)
test('long future and overlong commands cannot enable input', function()
    for _,raw in ipairs({command(2,2,2501,1600), command(2,2,2500,2001), command(2,2,2500,1600)..'x', string.rep('x',513)}) do
        local s=resumed(); s:update(raw,1000); assert(s.paused and not s.desired)
    end
end)
test('close clears input even without a valid input lease', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    s:update(command(3,5,0),1100); s:consumed(false,2,1100)
    assert(s.closed and s.paused and s.ack_seq==3 and not s.held)
end)
test('script error revokes desired input', function()
    local s=resumed(); s:update(command(2,2,2500,1600),1000)
    s:fail('script_error'); assert(s.paused and not s.desired)
end)
test('immutable command publication advances without replacing the active file', function()
    local s=M.new(session,42)
    assert(M.readCommand(s)==nil)
    local first=command(1,1,2500)
    local f=assert(io.open('input.0.txt','wb')); f:write(first); f:close()
    assert(M.readCommand(s)==first)
    local second=command(2,4,2500)
    f=assert(io.open('input.1.txt','wb')); f:write(second); f:close()
    assert(M.readCommand(s)==second)
    assert(M.readCommand(s)==second)
    os.remove('input.0.txt'); os.remove('input.1.txt')
end)
test('missing active generation does not fall back to an old command', function()
    local s=M.new(session,42)
    local f=assert(io.open('input.0.txt','wb')); f:write(command(1,1,2500)); f:close()
    assert(M.readCommand(s)); os.remove('input.0.txt')
    assert(M.readCommand(s)==nil)
end)
test('short new generation is returned for strict rejection', function()
    local s=M.new(session,42)
    local f=assert(io.open('input.0.txt','wb')); f:write(command(1,1,2500)); f:close()
    assert(M.readCommand(s))
    f=assert(io.open('input.1.txt','wb')); f:write('GQA1'); f:close()
    s:update(M.readCommand(s),1000)
    assert(s.paused and s.reason=='invalid')
    os.remove('input.0.txt'); os.remove('input.1.txt')
end)
test('unopened candidate cannot invalidate or renew the active publication', function()
    local s=M.new(session,42)
    local raw=command(1,1,2500)
    local f=assert(io.open('input.0.txt','wb')); f:write(raw); f:close()
    local original=io.open
    io.open=function(path,mode)
        if path=='input.1.txt' then return nil,'Permission denied',13 end
        return original(path,mode)
    end
    local ok,value=pcall(M.readCommand,s)
    io.open=original
    os.remove('input.0.txt')
    assert(ok and value==raw and s.generation==nil)
end)
local file=assert(io.open('lua-results.txt','w'))
file:write(table.concat(results,'\n'),'\n'); file:close()
